// Helper: create an Ed448 EVP_PKEY from a raw private key seed (57 bytes).
// Returns nullptr if the API is not yet implemented (stubbed).
static bssl::UniquePtr<EVP_PKEY> Ed448PrivKeyFromSeed(const uint8_t *seed) {
  EVP_PKEY *pkey = EVP_PKEY_new_raw_private_key(EVP_PKEY_ED448, nullptr,
                                                 seed, 57);
  if (pkey == nullptr) {
    // Ed448 not yet implemented — stub path
    ERR_clear_error();
    return nullptr;
  }
  return bssl::UniquePtr<EVP_PKEY>(pkey);
}

// Helper: create an Ed448 EVP_PKEY from a raw public key (57 bytes).
static bssl::UniquePtr<EVP_PKEY> Ed448PubKeyFromRaw(const uint8_t *pub) {
  EVP_PKEY *pkey = EVP_PKEY_new_raw_public_key(EVP_PKEY_ED448, nullptr,
                                                pub, 57);
  if (pkey == nullptr) {
    ERR_clear_error();
    return nullptr;
  }
  return bssl::UniquePtr<EVP_PKEY>(pkey);
}

// Helper: sign a message using Ed448 private key via EVP_DigestSign.
// Returns true if signing succeeded, false otherwise.
static bool Ed448Sign(uint8_t sig_out[114], EVP_PKEY *pkey,
                      const uint8_t *msg, size_t msg_len) {
  bssl::UniquePtr<EVP_MD_CTX> md_ctx(EVP_MD_CTX_new());
  if (!md_ctx ||
      !EVP_DigestSignInit(md_ctx.get(), nullptr, nullptr, nullptr, pkey)) {
    return false;
  }
  size_t sig_len = 114;
  if (!EVP_DigestSign(md_ctx.get(), sig_out, &sig_len, msg, msg_len)) {
    return false;
  }
  return sig_len == 114;
}

// Helper: verify a signature using Ed448 public key via EVP_DigestVerify.
static bool Ed448Verify(EVP_PKEY *pkey, const uint8_t *msg, size_t msg_len,
                        const uint8_t *sig, size_t sig_len) {
  bssl::UniquePtr<EVP_MD_CTX> md_ctx(EVP_MD_CTX_new());
  if (!md_ctx ||
      !EVP_DigestSignInit(md_ctx.get(), nullptr, nullptr, nullptr, pkey)) {
    // Try DigestVerifyInit for public-key-only
    md_ctx.reset(EVP_MD_CTX_new());
    if (!md_ctx ||
        !EVP_DigestVerifyInit(md_ctx.get(), nullptr, nullptr, nullptr, pkey)) {
      return false;
    }
  } else {
    // Re-init for verify
    md_ctx.reset(EVP_MD_CTX_new());
    if (!md_ctx ||
        !EVP_DigestVerifyInit(md_ctx.get(), nullptr, nullptr, nullptr, pkey)) {
      return false;
    }
  }
  return EVP_DigestVerify(md_ctx.get(), sig, sig_len, msg, msg_len) == 1;
}

// ============================================================================
// Test: RFC 8032 Section 5.2.6 KAT — Deterministic Signing
// Acceptance criteria: #6 (sign output matches known-answer vectors)
// ============================================================================
TEST(Ed448KATTest, RFC8032SignVerify) {
  for (const auto &vec : kRFC8032Vectors) {
    SCOPED_TRACE(vec.name);

    // Create private key from seed
    auto pkey = Ed448PrivKeyFromSeed(vec.privkey);
    if (!pkey) {
      // Ed448 not yet implemented — skip gracefully
      GTEST_SKIP() << "Ed448 EVP_PKEY_new_raw_private_key not yet implemented";
      return;
    }

    // Verify public key derivation (acceptance criterion #2)
    uint8_t pub_out[57];
    size_t pub_len = sizeof(pub_out);
    ASSERT_TRUE(EVP_PKEY_get_raw_public_key(pkey.get(), pub_out, &pub_len));
    ASSERT_EQ(57u, pub_len);
    EXPECT_EQ(Bytes(vec.pubkey, 57), Bytes(pub_out, 57))
        << "Public key derivation mismatch for " << vec.name;

    // Sign and compare to known answer (acceptance criterion #6)
    uint8_t sig[114];
    ASSERT_TRUE(Ed448Sign(sig, pkey.get(), vec.msg, vec.msg_len))
        << "Signing failed for " << vec.name;
    EXPECT_EQ(Bytes(vec.sig, 114), Bytes(sig, 114))
        << "Signature mismatch for " << vec.name;

    // Verify the signature (acceptance criterion #5: sign-then-verify round-trip)
    auto pub_pkey = Ed448PubKeyFromRaw(vec.pubkey);
    ASSERT_TRUE(pub_pkey);
    EXPECT_TRUE(Ed448Verify(pub_pkey.get(), vec.msg, vec.msg_len, sig, 114))
        << "Verification failed for " << vec.name;
  }
}

