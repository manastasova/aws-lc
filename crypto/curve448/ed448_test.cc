// Acceptance criteria: #1, #2, #3
// ============================================================================
TEST(Ed448KATTest, RawKeyRoundTrip) {
  for (const auto &vec : kRFC8032Vectors) {
    SCOPED_TRACE(vec.name);

    // Create from private seed
    auto priv_pkey = Ed448PrivKeyFromSeed(vec.privkey);
    if (!priv_pkey) {
      GTEST_SKIP() << "Ed448 not yet implemented";
      return;
    }

    // Criterion #1: EVP_PKEY_id == EVP_PKEY_ED448
    EXPECT_EQ(EVP_PKEY_ED448, EVP_PKEY_id(priv_pkey.get()));

    // Criterion #3: raw key accessors round-trip
    uint8_t priv_out[57];
    size_t priv_len = sizeof(priv_out);
    ASSERT_TRUE(
        EVP_PKEY_get_raw_private_key(priv_pkey.get(), priv_out, &priv_len));
    ASSERT_EQ(57u, priv_len);
    EXPECT_EQ(Bytes(vec.privkey, 57), Bytes(priv_out, 57));

    uint8_t pub_out[57];
    size_t pub_len = sizeof(pub_out);
    ASSERT_TRUE(
        EVP_PKEY_get_raw_public_key(priv_pkey.get(), pub_out, &pub_len));
    ASSERT_EQ(57u, pub_len);
    EXPECT_EQ(Bytes(vec.pubkey, 57), Bytes(pub_out, 57));

    // Create from public key only (criterion #1)
    auto pub_pkey = Ed448PubKeyFromRaw(vec.pubkey);
    ASSERT_TRUE(pub_pkey);
    EXPECT_EQ(EVP_PKEY_ED448, EVP_PKEY_id(pub_pkey.get()));

    uint8_t pub_out2[57];
    size_t pub_len2 = sizeof(pub_out2);
    ASSERT_TRUE(
        EVP_PKEY_get_raw_public_key(pub_pkey.get(), pub_out2, &pub_len2));
    ASSERT_EQ(57u, pub_len2);
    EXPECT_EQ(Bytes(vec.pubkey, 57), Bytes(pub_out2, 57));
  }
}

